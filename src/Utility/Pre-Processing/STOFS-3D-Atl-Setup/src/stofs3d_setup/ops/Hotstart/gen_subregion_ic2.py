"""Setup-local hotstart subregion interpolation with masked-cell-safe lookup.

Adapted from ``schism_py_pre_post.Shared_modules.gen_subregion_ic2`` so the
STOFS setup workflow can keep its hotstart behavior with local fixes.
"""

import os

import netCDF4 as nc
import numpy as np
import pandas as pd
import schism_py_pre_post
from pylib import schism_grid, read_schism_bpfile, inside_polygon
from scipy.interpolate import griddata, Rbf
from schism_py_pre_post.Geometry.interp import inverse_distance_weighting


def _nearest_valid_hycom_index(
    valid_lon: np.ndarray,
    valid_lat: np.ndarray,
    valid_flat_indices: np.ndarray,
    grid_shape: tuple[int, int],
    lon: float,
    lat: float,
) -> tuple[int, int]:
    """Return the grid index of the nearest unmasked HYCOM point."""
    delta_lon = valid_lon - lon
    delta_lat = valid_lat - lat
    distance_squared = delta_lon * delta_lon + delta_lat * delta_lat
    nearest_flat_index = valid_flat_indices[np.argmin(distance_squared)]
    return np.unravel_index(nearest_flat_index, grid_shape)


def gen_subregion_ic_stofs3d(
    wdir=None,
    obsdir=None,
    hycom_TS_file=None,
    date_str='2000-01-01',
    n_nei=6,
):
    '''
    Generate initial condition based on HYCOM and Observations
    in the subregion defined by ecgc_sub_grid.reg

    Inputs:
        wdir: working directory, where the model grid files are located
        obsdir: directory where the observations are downloaded
        hycom_TS_file: temperature and salinity file from HYCOM
        date_str: date string in the format YYYY-MM-DD
        n_nei: number of neighbors for inverse distance weighting,
            also used as a minimum number of observations required,
            if less than n_nei, exception will be raised
        ecgc_sub_grid.reg: region file defining the subregion to be modified
        ecgc_shoreline_sal.txt: manually defined shoreline for salinity interpolation
    
    Outputs:
        ecgc_coastal_tem.gr3: initial temperature on the model grid
        ecgc_coastal_sal.gr3: initial salinity on the model grid
    '''

    # copy datafiles
    mydir = os.path.dirname(schism_py_pre_post.__file__)
    os.system(f'cp {mydir}/Datafiles/ecgc_sub_grid.reg {wdir}')
    os.system(f'cp {mydir}/Datafiles/ecgc_shoreline_sal.txt {wdir}')

    var_dict = {
        'tem': {'interp_method': 2, 'f_ecgc_shoreline': None},
        'sal': {'interp_method': 1, 'f_ecgc_shoreline': 'ecgc_shoreline_sal.txt'},
    }

    for var in ['tem', 'sal']:
        # ----------------------------------------------------------------------------------
        # -----------------inputs--------------------------
        # ----------------------------------------------------------------------------------
        # wdir = '/sciclone/schism10/feiye/From_Nabi/RUN02/Hotstart_v1/'
        interp_method = var_dict[var]['interp_method']  # recommended: 1 sal; 2 tem
        # USGS data, generated by download_usgs_with_api-----------------
        f_usgs_coastal = f'{obsdir}/mean_{var}_xyz_{date_str}'

        # Manually defined coastal shoreline, which will take HYCOM values,
        # The purpose is to improve the interpolation along the shoreline
        # Not need for temperature because the horizontal gradient is small compared to salinity
        # The "z" value in the file will be replaced by the interpolated value from HYCOM
        if var_dict[var]['f_ecgc_shoreline'] is not None:
            f_ecgc_shoreline = wdir + var_dict[var]['f_ecgc_shoreline']
        else:
            f_ecgc_shoreline = None

        # HYCOM file, only used for interpolating values on f_ecgc_shoreline
        # hycom_TS_file = '/sciclone/schism10/feiye/Coastal_Act/Hot/13c/TS_1.nc'

        # Define sub region within which {var} is to be modified/x_ma
        f_grid_in = wdir + 'hgrid.gr3'
        # this region is manually made, which covers the entire watershed area
        f_sub_region = wdir + 'ecgc_sub_grid.reg'

        # outputs:
        # same as f_grid_in, but dp will be interpolated from f_usgs_coastal and f_ecgc_shoreline within f_sub_region
        f_grid_out = wdir + 'ecgc_coastal_' + var + '.gr3'

        # ----------------------------------------------------------------------------------
        # -----------------read region--------------------------
        # ----------------------------------------------------------------------------------
        region = read_schism_bpfile(f_sub_region, fmt=1)

        # ----------------------------------------------------------------------------------
        # -----------------load txt--------------------------
        # ----------------------------------------------------------------------------------
        # usgs coastal watershed
        usgs_coastal = np.array(pd.read_csv(f_usgs_coastal, delimiter=' ', header=None).values[:, :-1]).astype(float)
        if usgs_coastal.shape[0] < n_nei:
            raise ValueError(
                f'not enough observations for {var} in {f_usgs_coastal}, '
                f'{usgs_coastal.shape[0]} < {n_nei}'
            )

        # shoreline
        if f_ecgc_shoreline is None:
            ecgc_shoreline = None
        else:
            ecgc_shoreline = np.loadtxt(f_ecgc_shoreline)

        # ----------------------------------------------------------------------------------
        # -----------------load netcdf--------------------------
        # ----------------------------------------------------------------------------------
        if f_ecgc_shoreline is not None:
            variable_name = 'salinity' if var == 'sal' else 'temperature'
            with nc.Dataset(hycom_TS_file) as ds:
                lon = np.asarray(ds['xlon'][:])
                lat = np.asarray(ds['ylat'][:])
                surface_values = ds[variable_name][0, 0, :, :]

            xx, yy = np.meshgrid(lon, lat)
            valid = ~np.ma.getmaskarray(surface_values)
            valid &= np.isfinite(xx) & np.isfinite(yy)
            valid &= np.isfinite(np.ma.getdata(surface_values))

            valid_flat_indices = np.flatnonzero(valid.ravel())
            if valid_flat_indices.size == 0:
                raise ValueError(f'No valid HYCOM surface points in {hycom_TS_file}')

            valid_lon = xx.ravel()[valid_flat_indices]
            valid_lat = yy.ravel()[valid_flat_indices]
            for i, shoreline_point in enumerate(ecgc_shoreline):
                if shoreline_point[2] > 1e-6:
                    if not np.isfinite(shoreline_point[:2]).all():
                        raise ValueError(
                            f'Non-finite shoreline coordinate at row {i + 1} '
                            f'in {f_ecgc_shoreline}'
                        )
                    ind = _nearest_valid_hycom_index(
                        valid_lon,
                        valid_lat,
                        valid_flat_indices,
                        valid.shape,
                        shoreline_point[0],
                        shoreline_point[1],
                    )
                    ecgc_shoreline[i, 2] = surface_values[ind]
            xyz = np.append(usgs_coastal, ecgc_shoreline, axis=0)
        else:
            xyz = usgs_coastal

        # ensure quality
        xyz_min = -99999
        xyz_max = 99999
        if var == 'sal':
            xyz_min = 0
            xyz_max = 42
        elif var == 'tem':
            xyz_min = -5
            xyz_max = 42
        box = [-150, -50, 0, 50]
        # remove invalid values
        idx = np.where((xyz[:, 2] >= xyz_min) & (xyz[:, 2] <= xyz_max))[0]
        xyz = xyz[idx, :]
        # remove invalid lon/lat
        idx = np.where((xyz[:, 0] >= box[0]) & (xyz[:, 0] <= box[1]))[0]
        xyz = xyz[idx, :]
        np.savetxt(f'{wdir}/ecgc_shoreline+coastal_{var}.txt', xyz, delimiter=' ')

        # ----------------------------------------------------------------------------------
        # -----------------load hgrid--------------------------
        # ----------------------------------------------------------------------------------
        gd = schism_grid(f_grid_in)
        idx = (inside_polygon(np.c_[gd.x, gd.y], region.x, region.y) == 1)
        gd_x = gd.x[idx]
        gd_y = gd.y[idx]

        # gd = Hgrid("/sciclone/schism10/feiye/ICOGS/RUN06f/Hot_and_3Dth_for_06h/ecgc.gr3")
        # gd.get_nodes()
        # gd_x = gd.node_np[:, 1]
        # gd_y = gd.node_np[:, 2]

        # ----------------------------------------------------------------------------------
        # -----------------interpolation--------------------------
        # ----------------------------------------------------------------------------------
        if interp_method == 0:  # Rbf interpolator
            interpolator = Rbf(xyz[:, 0], xyz[:, 1], xyz[:, 2], function='linear')
            z_interp = interpolator(gd_x, gd_y)
            z_interp = np.maximum(z_interp, min(xyz[:, 2]))
            z_interp = np.minimum(z_interp, max(xyz[:, 2]))
        elif interp_method == 1:  # linear
            z_interp = griddata(xyz[:, 0:2], xyz[:, 2], (gd_x, gd_y), method='linear')
        elif interp_method == 2:  # inverse-distance weighted
            # idw_tree = idw.tree(xyz[:, 0:2], xyz[:, 2])  # see github: paulbrodersen/inverse_distance_weighting
            # z_interp = idw_tree(np.transpose(np.vstack([gd_x, gd_y])))
            z_interp = inverse_distance_weighting(
                X=xyz[:, 0:2], val=xyz[:, 2],
                Xq=np.transpose(np.vstack([gd_x, gd_y])), n_nei=n_nei
            )
        else:
            raise Exception(f'unknown interp_method {interp_method}')
        nan_idx = np.where(np.isnan(z_interp))

        # dealing with nan
        z_interp_nearest = griddata(xyz[:, 0:2], xyz[:, 2], (gd_x, gd_y), method='nearest')
        z_interp[nan_idx] = z_interp_nearest[nan_idx]

        gd.dp[:] = -9999
        gd.dp[idx] = z_interp
        gd.write_hgrid(f_grid_out)
